"""Publish the downloadable data packs from the local data repository clone.

The app bundles only the English example sentences and their part-of-speech
index (assets/examples/en.json). The per-language translations are large, so
each device downloads just the one for its translation language:

    manifest  https://raw.githubusercontent.com/<repo>/main/manifest.json
    files     https://cdn.jsdelivr.net/gh/<repo>@<tag>/<path>

Files are served from an immutable tag, so the CDN never mixes versions; the
manifest names the current tag.

Data repository (github.com/overlayered01/vocabulary-data), cloned next to the
app as ../vocabulary-data:
    examples/<lang>.json   published packs (written by tool/build_examples.py)
    machine/<lang>.json    merged machine translations (tool/mt_chunks.py merge)
    mt/                    machine-translation work chunks (not committed)

Usage:
    python -X utf8 tool/build_examples.py --data <download dir>
    python -X utf8 tool/publish_packs.py [--dry-run]
"""
import argparse
import hashlib
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT.parent / "vocabulary-data"

README = """# Vocab with Examples data

Downloadable data for the Vocab with Examples app. Generated by the app's
`tool/build_examples.py`, `tool/mt_chunks.py` and `tool/publish_packs.py`;
do not edit `examples/` or `manifest.json` by hand.

- `examples/<lang>.json`: translations of the app's bundled English example
  sentences, keyed by Tatoeba sentence id. Downloaded by the app.
  - `human`: translations from [Tatoeba](https://tatoeba.org), CC BY 2.0 FR.
  - `machine`: machine translations of the same sentences (labelled as such in
    the app), CC BY 2.0 FR as derivatives of the Tatoeba sentences.
- `machine/<lang>.json`: all accepted machine translations (source for
  `examples/`).
- `mt/`: work chunks for machine translation (ignored by git).
- `manifest.json`: current tag, size and checksum of each file.
"""


def run(*args: str, cwd: pathlib.Path) -> str:
    return subprocess.run(
        args, cwd=cwd, check=True, capture_output=True, text=True
    ).stdout.strip()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=pathlib.Path, default=DATA)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    data: pathlib.Path = args.data
    if not (data / ".git").exists():
        raise SystemExit(
            f"{data} is not a git clone of the data repository "
            "(gh repo clone overlayered01/vocabulary-data)"
        )

    manifest_path = data / "manifest.json"
    manifest = (
        json.loads(manifest_path.read_text(encoding="utf-8"))
        if manifest_path.exists()
        else {}
    )
    previous = manifest.get("examples", {})

    files = {}
    for path in sorted((data / "examples").glob("*.json")):
        raw = path.read_bytes()
        pack = json.loads(raw)
        files[path.stem] = {
            "path": f"examples/{path.name}",
            "bytes": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
            "human": len(pack.get("human", {})),
            "machine": len(pack.get("machine", {})),
        }
    if not files:
        raise SystemExit(f"no packs in {data / 'examples'}")
    for code, info in files.items():
        print(f"{code}: {info['bytes'] / 1e6:.2f}MB "
              f"human {info['human']} machine {info['machine']}")

    (data / "README.md").write_text(README, encoding="utf-8")
    (data / ".gitignore").write_text("mt/\n", encoding="utf-8")
    if files == previous.get("files"):
        print("packs unchanged", previous.get("tag"))
        tag = None
    else:
        version = previous.get("version", 0) + 1
        tag = f"examples-v{version}"
        manifest["examples"] = {"version": version, "tag": tag, "files": files}
        manifest_path.write_text(
            json.dumps(manifest, ensure_ascii=False, indent=1) + "\n",
            encoding="utf-8",
        )
    if args.dry_run:
        print("dry run: not committed", tag or "")
        return

    run("git", "add", "-A", cwd=data)
    if not run("git", "status", "--porcelain", cwd=data):
        print("nothing to commit")
        return
    run("git", "commit", "-m", f"Examples {tag}" if tag else "Update data",
        cwd=data)
    push = ["git", "push", "origin", "HEAD:main"]
    if tag:
        run("git", "tag", tag, cwd=data)
        push.append(tag)
    run(*push, cwd=data)
    print("published", tag or "(no new pack version)")


if __name__ == "__main__":
    main()
